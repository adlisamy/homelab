#!/usr/bin/env bash
# Generate infra/ansible/inventory/lab/hosts.yaml from `terraform output -json`.
# Run AFTER `terraform apply` (or `terraform refresh`). Does NOT run Ansible.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TF_DIR="${REPO_ROOT}/infra/terraform"
OUT="${REPO_ROOT}/infra/ansible/inventory/lab/hosts.yaml"
SSH_USER="ubuntu"
SSH_KEY="~/.ssh/kvm_ed25519"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --tf-dir) TF_DIR="$2"; shift 2 ;;
    --output) OUT="$2"; shift 2 ;;
    --ssh-user) SSH_USER="$2"; shift 2 ;;
    --ssh-key) SSH_KEY="$2"; shift 2 ;;
    *) echo "Unknown: $1" >&2; exit 1 ;;
  esac
done

JSON="$(cd "$TF_DIR" && terraform output -json)"
mapfile -t NAMES < <(jq -r '.vm_name.value[]' <<<"$JSON")

declare -A IP
MISSING=0
for n in "${NAMES[@]}"; do
  ip="$(jq -r --arg n "$n" '.primary_ip.value[$n] // ""' <<<"$JSON")"
  if [[ ! "$ip" =~ ^[0-9.]+$ ]]; then
    echo "[WARN] $n: IP not ready (run 'terraform refresh')" >&2
    MISSING=1
  else
    IP["$n"]="$ip"
  fi
done

mkdir -p "$(dirname "$OUT")"
{
  echo "# AUTO-GENERATED by ops/scripts/generate_inventory.sh - DO NOT EDIT."
  echo "all:"
  echo "  children:"
  echo "    k3s_servers:"
  echo "      hosts:"
  for n in "${NAMES[@]}"; do
    [[ "$n" == *-01 ]] && [[ -n "${IP[$n]:-}" ]] && {
      echo "        $n:"
      echo "          ansible_host: ${IP[$n]}"
      echo "          ansible_user: $SSH_USER"
      echo "          ansible_ssh_private_key_file: $SSH_KEY"
    }
  done
  echo "    k3s_agents:"
  echo "      hosts:"
  for n in "${NAMES[@]}"; do
    [[ "$n" != *-01 ]] && [[ -n "${IP[$n]:-}" ]] && {
      echo "        $n:"
      echo "          ansible_host: ${IP[$n]}"
      echo "          ansible_user: $SSH_USER"
      echo "          ansible_ssh_private_key_file: $SSH_KEY"
    }
  done
} > "$OUT"

echo "[OK] Inventory written to $OUT"
for n in "${NAMES[@]}"; do echo "  - $n: ${IP[$n]:-N/A}"; done
echo "Next: cd infra/ansible && ansible-playbook -i inventory/lab playbooks/site.yaml"
exit "$MISSING"